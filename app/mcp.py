def launcher_note() -> str:
    """What `charter`, by name, runs for a newly started program. Agent hosts set
    up with Connect Agents start this copy by its full path, so PATH only
    decides what a terminal, or an agent running `charter propose`, reaches.
    Reads PATH; changes nothing."""
    from . import on_path
    try:
        path = on_path.fresh_path(on_path.Registry()) if os.name == "nt"             else os.environ.get("PATH", "")
        found = on_path.resolve(on_path.NAME, path)
    except OSError:
        found = None
    if on_path.is_launcher(found, on_path.LAUNCHERS):
        return "`charter`, typed in a new terminal, runs this copy"
    if found:
        return (f"`charter`, typed in a new terminal, runs another copy, from {os.path.dirname(found)}; "
                f"remove {os.path.dirname(found)} from PATH so that this copy is the one found. Agent "
                "hosts set up with Connect Agents start this copy by its full path")
    return ("`charter` is not on PATH for new terminals; agent hosts set up with Connect Agents do not "
            "need it, since they start this copy by its full path")
