"""`charter read`: Command-Line Access, read-only, to one Agent Context.

    charter read --context <absolute-folder>                      AGENT-CONTEXT.md
    charter read --context <absolute-folder> --list               the governing documents
    charter read --context <absolute-folder> --document <ref>     one document
    charter read --context <absolute-folder> --document <ref> --heading <heading>
    … [--json]

Agent Context as the Project Asset §9. The fallback for an agent that can run
commands but has no usable MCP: each form answers exactly as its MCP tool does
(`get_context`, `list_governing_documents`, `get_document`,
`get_document_section`), from the same validation and the same byte-checked
reads (`app.mcp`), on every call.

`--context` names the Agent Context by its absolute path, every time. Nothing
else ever chooses the folder: no current folder, relative path, search,
environment variable, configuration, Recent or remembered folder.

It writes only to standard output — text ending with `END_MARKER` on its own
last line, or exactly one JSON object — and never to standard error. It creates
and changes no private state, records no activity and touches nothing in
Recent: it only reads existing private state, as MCP does, to learn whether a
Charter write to the folder was interrupted. Exit 0 when served, 1 when
refused, 2 for `bad-arguments`. There is no proposal route.
"""
from __future__ import annotations

import json
import os
import sys
from typing import Any, Dict, List, Optional, Tuple

from . import mcp

END_MARKER = "<<<END CHARTER READ>>>"

EXIT_SERVED, EXIT_REFUSED, EXIT_USAGE = 0, 1, 2

# §9: ends every refusal for a named Agent Context that is unavailable.
DO_NOT_RELY = ("Do not rely on Charter context you retrieved earlier in this session. Report to "
               "the person that Charter context is unavailable, rather than guessing or continuing "
               "from earlier context.")
_INSTRUCTIONS = ("Run the exact command your project instructions give, and do not search for an "
                 "Agent Context.")
# §9: the usage errors that name no Agent Context, exactly, and without DO_NOT_RELY.
NOT_NAMED = "No Agent Context was named, so nothing is served. " + _INSTRUCTIONS
NOT_ABSOLUTE = "The Agent Context must be named by its full path, so nothing is served. " + _INSTRUCTIONS
BAD_OPTIONS = ("An option is missing, unknown, repeated, too long or without a value, so nothing "
               "is served. " + _INSTRUCTIONS)
NO_FOLDER = ("No Agent Context could be read at the folder this command names, so nothing is "
             "served. A person must check that folder in Charter. " + DO_NOT_RELY)
# §9: the one retry, exactly.
CHANGED_DURING_READ = ("A file changed while it was being read, so nothing was returned. Run the "
                       "exact same command once more. If you have already run it once more after "
                       "this result, or that run does not succeed, do not run it again. "
                       + DO_NOT_RELY)

_LIST_HINT = "Name a document by the `path` or `id` that `charter read --list` returns."
# Each code's message: MCP's, where §9 changes nothing but a tool's name.
MESSAGES = {
    "context-invalid": mcp.MESSAGES["context-invalid"] + " " + DO_NOT_RELY,
    "context-unclean": mcp.MESSAGES["context-unclean"] + " " + DO_NOT_RELY,
    "map-outdated": mcp.MESSAGES["map-outdated"] + " " + DO_NOT_RELY,
    "charter-outdated": ("This Agent Context was generated by a newer version of Charter than this "
                         "copy, so nothing is served; the Agent Context is not at fault. A person "
                         "must update this copy of Charter. " + DO_NOT_RELY),
    "changed-during-read": CHANGED_DURING_READ,
    "not-governing": "That is not a current governing document. " + _LIST_HINT,
    "unsafe-path": "That is not a name Charter listed. " + _LIST_HINT,
    "heading-missing": mcp.MESSAGES["heading-missing"],
    "heading-ambiguous": mcp.MESSAGES["heading-ambiguous"],
    "bad-arguments": BAD_OPTIONS,
}
CODES = tuple(MESSAGES)

_VALUED = ("--context", "--document", "--heading")
_FLAGS = ("--list", "--json")


class Usage(Exception):
    """A command line that names no usable request: `bad-arguments`, exit 2."""

    def __init__(self, message: str = BAD_OPTIONS):
        super().__init__(message)
        self.message = message


def absolute(path: str) -> bool:
    """A full path: on Windows one that names its drive (or a UNC share) too,
    so `\\folder` and `C:folder`, which depend on the current drive or its
    current folder, are not."""
    if not os.path.isabs(path):
        return False
    return os.name != "nt" or bool(os.path.splitdrive(path)[0])


def parse(argv: List[str]) -> Tuple[Dict[str, Any], bool]:
    """(the options, whether `--json` was asked for), or Usage. `--json` is
    learnt first, so even a usage error answers in the form asked for."""
    options: Dict[str, Any] = {}
    as_json = "--json" in argv
    problem: Optional[str] = None
    i = 0
    while i < len(argv):
        word = argv[i]
        name, sep, value = word.partition("=")
        if name in _FLAGS and not sep:
            key, given = name, True
        elif name in _VALUED and sep:
            key, given = name, value
        elif name in _VALUED and i + 1 < len(argv) and not argv[i + 1].startswith("--"):
            key, given = name, argv[i + 1]
            i += 1
        elif name in _VALUED:
            key, given = name, ""  # no value: an empty one
        else:
            problem = problem or BAD_OPTIONS
            i += 1
            continue
        if key in options:
            problem = problem or BAD_OPTIONS
        options[key] = given
        i += 1
    # The Agent Context first: a command that names none says so, whatever else is wrong.
    context = options.get("--context")
    if not isinstance(context, str) or not context:
        raise Usage(NOT_NAMED)
    if not absolute(context):
        raise Usage(NOT_ABSOLUTE)
    if problem:
        raise Usage(problem)
    for key in ("--document", "--heading"):
        if key in options and not options[key]:
            raise Usage()
    if ("--list" in options and ("--document" in options or "--heading" in options)) \
            or ("--heading" in options and "--document" not in options):
        raise Usage()
    return options, as_json


def request(options: Dict[str, Any]) -> Tuple[str, Dict[str, str]]:
    """The MCP tool, and its arguments, that these options are the equivalent of."""
    if "--list" in options:
        return "list_governing_documents", {}
    if "--heading" in options:
        return "get_document_section", {"document": options["--document"],
                                        "heading": options["--heading"]}
    if "--document" in options:
        return "get_document", {"document": options["--document"]}
    return "get_context", {}


def _readable_folder(folder: str) -> bool:
    """Whether `folder` is a folder this process can list, not a link to one."""
    if os.path.islink(folder) or not os.path.isdir(folder):
        return False
    try:
        with os.scandir(folder):
            return True
    except OSError:
        return False


def serve(folder: str, name: str, args: Dict[str, str]) -> Tuple[str, Dict[str, Any]]:
    """The text and structured payload for one request, or mcp.Refusal with a
    command code. Validated whole before and after, exactly as an MCP call is
    (`mcp.Server._call`), with no activity and nothing written anywhere."""
    if not _readable_folder(folder):
        raise mcp.Refusal("context-invalid", NO_FOLDER)
    args = mcp._check_arguments(name, args)
    exam = mcp.examine(folder)
    start = mcp.fingerprint(exam)
    text, payload, _seen = mcp.answer(name, args, exam)
    mcp.settled(folder, start)
    return text, payload


def result(argv: List[str]) -> Tuple[bytes, int]:
    """The exact bytes to write to standard output, and the exit code."""
    as_json = "--json" in argv
    try:
        options, as_json = parse(argv)
        folder = os.path.normpath(options["--context"])
        name, args = request(options)
        text, payload = serve(folder, name, args)
    except Usage as usage:
        return _refusal("bad-arguments", usage.message, as_json), EXIT_USAGE
    except mcp.Refusal as refusal:
        code = "charter-outdated" if refusal.reason == "server-outdated" else refusal.reason
        message = _message(code, refusal.message)
        return _refusal(code, message, as_json), \
            EXIT_USAGE if code == "bad-arguments" else EXIT_REFUSED
    except Exception:  # noqa: BLE001 — fail closed; nothing private reaches the agent
        return _refusal("context-invalid", MESSAGES["context-invalid"], as_json), EXIT_REFUSED
    if as_json:
        return _json(dict({"result": "served"}, **payload)), EXIT_SERVED
    body = text if text.endswith("\n") else text + "\n"
    return (body + END_MARKER + "\n").encode("utf-8"), EXIT_SERVED


def _message(code: str, given: str) -> str:
    """The command's message for a refusal raised with MCP's: MCP's own
    integrity message, which already ends with DO_NOT_RELY, and the folder
    message are kept; every other is the command's own for its code."""
    if code == "context-invalid" and given.endswith(DO_NOT_RELY):
        return given
    if code == "context-invalid" and given == NO_FOLDER:
        return given
    if code == "bad-arguments":
        return BAD_OPTIONS
    return MESSAGES[code]


def _refusal(code: str, message: str, as_json: bool) -> bytes:
    if as_json:
        return _json({"result": "refused", "reason": code, "message": message})
    return f"{code}: {message}\n".encode("utf-8")


def _json(obj: Dict[str, Any]) -> bytes:
    # ASCII only, so no console code page can corrupt it.
    return (json.dumps(obj, ensure_ascii=True) + "\n").encode("ascii")


def main(argv: List[str]) -> int:
    """`charter read …`: one answer on standard output, nothing on standard error."""
    out = sys.stdout
    sys.stderr = open(os.devnull, "w")  # nothing on standard error, ever
    data, code = result(list(argv))
    try:
        out.buffer.write(data)
        out.buffer.flush()
    except AttributeError:  # a replaced stdout without a byte buffer (e.g. a test)
        out.write(data.decode("utf-8"))
        out.flush()
    except (OSError, ValueError):
        pass  # the reader went away; there is no one left to tell
    return code
