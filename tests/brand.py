    check(ac.TRANSACTION_PREFIX == ".charter-txn-", "new temporary files are `.charter-txn-`")
    with open(os.path.join(ROOT, "CHANGELOG.md"), encoding="utf-8") as fh:
        changelog = fh.read()
    current = changelog.split("\n## ", 2)[1]  # the newest release's section
    line = " ".join(current.split("**`charter` command:**", 1)[1].split("from the", 1)[0].split())
