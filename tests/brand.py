"""Charter's name, and nothing of its earlier one. Run: python -m tests.brand

Agent Context as the Project Asset §1: the product is Charter, its command is
`charter`, and Agent Context Manager is only a descriptive category. The
earlier name, Agent Context Manager (ACM), and its `acm` command appear only
where a person needs them to recognize or move earlier local material.

  * every public name is Charter's: the command, launchers, MCP server, console,
    generated map, proposal route, review material and schemas;
  * the Agent Context's own names and the approved technical exceptions are
    unchanged: `AGENT-CONTEXT.md`, `.agent-context.json`, `authoritative/`,
    the MCP tools, `acm-context-fingerprint/1`, a stored `acm` observation, and
    recognition of an earlier `.acm-txn-` temporary file;
  * the active source and the README name the earlier product only beside
    words that say it is the earlier name, and in the README's descriptor.
"""
from __future__ import annotations

import hashlib
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from app import __main__ as cli  # noqa: E402
from app import agent_context as ac  # noqa: E402
from app import connect, console, git_compare, impact, mcp, on_path, server  # noqa: E402
