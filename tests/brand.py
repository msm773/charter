def _active_files():
    for d, subs, names in os.walk(os.path.join(ROOT, "app")):
        subs[:] = [s for s in subs if s != "__pycache__"]
        for n in names:
            if n.endswith((".py", ".js", ".html", ".css")):
                yield os.path.join(d, n)
    for n in ("charter", "charter.cmd", "charter.py", ".gitattributes", "requirements.txt"):
        # `.gitattributes` belongs to a source checkout; a release does not carry it.
        if os.path.isfile(os.path.join(ROOT, n)):
            yield os.path.join(ROOT, n)


def _unexplained(path: str, lines, skip=lambda n: False):
    found = []
    for n, line in enumerate(lines):
        if skip(n):
            continue
        rest = line
        for token in ALLOWED_TOKENS:
            rest = rest.replace(token, "")
        if not EARLIER.search(rest):
            continue
        window = lines[max(0, n - NEAR): n + NEAR + 1]
        if not any(CONTEXT_WORDS.search(w) for w in window):
            found.append(f"{os.path.relpath(path, ROOT)}:{n + 1}: {line.strip()[:100]}")
    return found


def case_no_earlier_identity() -> None:
    print("\nthe earlier name appears only where it is said to be the earlier name")
    found = []
    for path in _active_files():
        with open(path, encoding="utf-8") as fh:
            found += _unexplained(path, fh.read().splitlines())
    check(not found, "active source, launchers and settings: " + ("clean" if not found else
                                                                    "\n    " + "\n    ".join(found)))

    readme = os.path.join(ROOT, "README.md")
    with open(readme, encoding="utf-8") as fh:
        lines = fh.read().splitlines()
    check(lines[:5] == ["# Charter", "", "*Agent Context Manager*", "",
                        "**One trusted context for every AI agent on your project.**"],
          "the README opens with Charter, its descriptor beneath it, then the tagline")
    found = _unexplained(readme, lines, skip=lambda n: n == 2)
    check(not found, "the README names Agent Context Manager only as its descriptor"
                     + ("" if not found else "\n    " + "\n    ".join(found)))


# Strings that must keep the earlier name exactly: the map Agent Context
# Manager generated, which Charter recognizes but never writes, and the stored
# names of its private-state folder and observations.
def _legacy_literals() -> set:
    return {before for _now, before in ac._LEGACY_WORDING} | {"acm", "ACM"}


def _docstrings(tree) -> set:
    import ast
    found = set()
    for node in ast.walk(tree):
        if isinstance(node, (ast.Module, ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef))                 and node.body and isinstance(node.body[0], ast.Expr)                 and isinstance(node.body[0].value, ast.Constant):
            found.add(id(node.body[0].value))
    return found


def _unexplained_strings(path: str) -> list:
    """Every string a Python module can show or return that names the earlier
    product without saying it is the earlier name. Python joins adjacent
    literals before this sees them, so a name split across lines, as in
    `"... Agent "` `"Context Manager ..."`, is one string here."""
    import ast
    with open(path, encoding="utf-8") as fh:
        tree = ast.parse(fh.read())
    legacy, docs, found = _legacy_literals(), _docstrings(tree), []
    for node in ast.walk(tree):
        if not (isinstance(node, ast.Constant) and isinstance(node.value, str)) or id(node) in docs:
            continue
        value = node.value
        if value in legacy:
            continue
        rest = value
        for token in ALLOWED_TOKENS:
            rest = rest.replace(token, "")
        if EARLIER.search(" ".join(rest.split())) and not CONTEXT_WORDS.search(value):
            found.append(f"{os.path.relpath(path, ROOT)}:{node.lineno}: {value.strip()[:100]}")
    return found


# A page string joined with `+`, possibly across lines: `"... Agent " + "Context Manager"`.
_JOIN = re.compile(r"""(["'`])\s*\+\s*(["'`])""")
_SPLIT_NAME = re.compile(r"Agent\s+Context\s+Manager")


def _unexplained_page_text(path: str) -> list:
    """The page's scripts and markup, with `+`-joined literals joined and
    whitespace runs, line breaks included, read as one space."""
    with open(path, encoding="utf-8") as fh:
        text = _JOIN.sub("", fh.read())
    found = []
    for m in _SPLIT_NAME.finditer(text):
        window = text[max(0, m.start() - 300): m.end() + 300]
        if not CONTEXT_WORDS.search(window):
            line = text.count("\n", 0, m.start()) + 1
            found.append(f"{os.path.relpath(path, ROOT)}:~{line}: {' '.join(window.split())[:100]}")
    return found


def case_no_split_earlier_name() -> None:
    print("\nthe earlier name is not hidden in a string split across lines or literals")
    found = []
    for path in _active_files():
        if path.endswith(".py"):
            found += _unexplained_strings(path)
        elif path.endswith((".js", ".html")):
            found += _unexplained_page_text(path)
    check(not found, "every string the source can show: " + ("clean" if not found else
                                                             "\n    " + "\n    ".join(found)))


def case_rendered_output() -> None:
    """What a person or agent is actually shown, whatever produced it."""
    print("\nwhat Charter prints and returns names Charter, not the earlier name")
    import json
    import shutil
    import subprocess
    import tempfile
    from app import manager
    from tests.agent_context import context, write
    from tests.harness import isolated_private_state
    root = context()
    state = tempfile.mkdtemp(prefix="charter-brand-state-")
    try:
        write(root, "CLAUDE.md", "# notes\n")
        os.makedirs(os.path.join(root, "authoritative", "empty"))
        with isolated_private_state():
            report = "\n".join(cli._report(manager.check(root, git=False)))
        check("CLAUDE.md" in report and not EARLIER.search(report),
              "`charter check` on a folder with strays names Charter as the one leaving them untouched")
        os.remove(os.path.join(root, "CLAUDE.md"))
        os.rmdir(os.path.join(root, "authoritative", "empty"))
        meta = os.path.join(root, ac.METADATA)
        with open(meta, encoding="utf-8") as fh:
            data = json.load(fh)
        with open(meta, "w", encoding="utf-8", newline="\n") as fh:
            json.dump(data, fh, indent=4)
        with isolated_private_state():
            report = "\n".join(cli._report(manager.check(root, git=False)))
        check(".agent-context.json" in report and not EARLIER.search(report),
              "a hand-reformatted `.agent-context.json` is reported as not in the form Charter generates")
        with open(meta, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(ac.render_metadata(ac.Settings.make("Test project"), data["sha256"]))
        proposal = json.dumps({"agent": "a", "operation": "create",
                               "target_path": "authority-candidates/x.md", "reason": "r",
                               "proposed_body": "---\ntitle: X\n---\n\nBody\n"})
        out = subprocess.run([sys.executable, os.path.join(ROOT, "tests", "_launch.py"), state,
                              "propose", "--context", "."], cwd=root, input=proposal,
                             capture_output=True, text=True, encoding="utf-8")
        check('"refused"' in out.stdout and "front" in out.stdout and not EARLIER.search(out.stdout),
              "an agent's refused proposal names Charter as setting a candidate's metadata")
    finally:
        shutil.rmtree(root, ignore_errors=True)
        shutil.rmtree(state, ignore_errors=True)


def run() -> int:
    case_public_names()
    case_unchanged()
    case_no_earlier_identity()
    case_no_split_earlier_name()
    case_rendered_output()
    print(f"\n{OK} All brand checks passed.")
    return 0


if __name__ == "__main__":
    sys.exit(run())
