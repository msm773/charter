OK = "ok"

# An earlier-name occurrence, in any spelling the source has used.
EARLIER = re.compile(r"Agent Context Manager|AgentContextManager|(?<![A-Za-z0-9])(?:ACM|acm)(?![A-Za-z0-9])")
# Approved technical exceptions, wherever they appear.
ALLOWED_TOKENS = ("acm-context-fingerprint/1", ".acm-txn-")
# A line may name the earlier product when it, or a line near it, says that is
# what it is.
CONTEXT_WORDS = re.compile(r"earlier", re.I)
NEAR = 5


def check(condition: bool, label: str) -> None:
    if not condition:
        print(f"  FAILED: {label}")
        raise SystemExit(1)
    print(f"  {OK} {label}")


